#!/bin/bash

SSHD_CONFIG="$HOME/.config/ssh/sshd_config"
# Функция для остановки sshd при получении сигнала
cleanup() {
    echo "Получен сигнал завершения. Останавливаем sshd..."
    # Здесь мы не можем "остановить" уже запущенный процесс sshd,
    # потому что он работает в том же процессе, что и скрипт.
    # Просто выходим из скрипта, и sshd автоматически завершится.
    exit 0
}

# Назначаем обработчики сигналов SIGINT (Ctrl+C) и SIGTERM
trap cleanup SIGINT SIGTERM

# Проверяем существование исполняемого файла и конфига
if [ ! -x "$SSHD_BIN" ]; then
    echo "Ошибка: Не найден исполняемый файл sshd: $SSHD_BIN"
    exit 1
fi

if [ ! -f "$SSHD_CONFIG" ]; then
    echo "Ошибка: Не найден конфигурационный файл: $SSHD_CONFIG"
    exit 1
fi

echo "Запускаем SSH-сервер..."
echo "Используется конфигурация: $SSHD_CONFIG"
echo "Для остановки нажмите Ctrl+C"

# Запускаем sshd в foreground (-D) с логированием в stderr (-e)
# -D: Не отключаться от терминала и не демонизироваться
# -e: Логировать ошибки в stderr вместо syslog
# -f: Указать путь к конфигурационному файлу
sshd -D -e -f $SSHD_CONFIG

# Этот код выполнится только если sshd сам завершится (что маловероятно)
echo "SSH-сервер завершил работу."
